set_1={1,2,3,4,5}
set_2={3,4,5,6,7}

print(f"Union of the sets is: {set_1.union(set_2)}")
print(f"Intersection of the sets is: {set_1.intersection(set_2)}")
print(f"Set_1 - Set_2 of the sets is: {set_1.difference(set_2)}")
print(f"Set_2 - Set_1 of the sets is: {set_2.difference(set_1)}")
print(f"Symmetric Difference of the sets is: {set_1.symmetric_difference(set_2)}")