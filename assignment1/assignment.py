print(f"-= with {num2}: {num1}")
num1*=num2
print(f"*= with {num2}: {num1}")
num1/=num2
print(f"/= with {num2}: {num1}")
num1%=num2
print(f"%= with {num2}: {num1}")
num1**=num2
print(f"**= with {num2}: {num1}")
